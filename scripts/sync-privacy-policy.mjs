#!/usr/bin/env node
// Fetches the published Google Doc privacy policy, parses its (structurally
// flat — no real <h1-6>/<ul> tags, everything is <p>) content into headings /
// paragraphs / bullet lists using positional heuristics, and writes a typed
// data file that PrivacyPolicy.tsx renders with the site's own styling.
//
// Run manually: node scripts/sync-privacy-policy.mjs
// Run automatically by: .github/workflows/sync-privacy-policy.yml

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import * as cheerio from 'cheerio';

const DOC_URL =
  'https://docs.google.com/document/d/e/2PACX-1vSUAWMYdMYIzpFnxHc-k4OJo_DGWHf0MA1nk06g9XpSRsx3rUFHrvKaZz__gYSR2tlpW0jaGkLk_2XP/pub';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUTPUT_PATH = path.resolve(__dirname, '../src/content/privacyPolicy.generated.ts');

async function main() {
  const res = await fetch(DOC_URL);
  if (!res.ok) {
    throw new Error(`Failed to fetch privacy policy doc: ${res.status} ${res.statusText}`);
  }
  const html = await res.text();
  const $ = cheerio.load(html);

  const paragraphs = $('.doc-content > p').toArray();
  if (paragraphs.length < 5) {
    // Refuse to overwrite good content with garbage if Google's markup
    // shape ever changes underneath us (better a stale page than a broken one).
    throw new Error(
      `Only found ${paragraphs.length} paragraphs in the doc — the export format may have changed. Aborting without writing.`
    );
  }

  const lines = paragraphs.map(p => $(p).text().replace(/\s+/g, ' ').trim());

  let title = '';
  const meta = [];
  const blocks = [];
  let pendingList = null;
  let prevWasBlank = true; // start of document counts as "preceded by a blank line"
  let sawFirstHeading = false;

  const flushList = () => {
    if (pendingList) {
      blocks.push(pendingList);
      pendingList = null;
    }
  };

  for (const line of lines) {
    if (!line) {
      prevWasBlank = true;
      continue;
    }

    if (line.startsWith('- ')) {
      const item = line.slice(2).trim();
      if (!pendingList) pendingList = { type: 'ul', items: [] };
      pendingList.items.push(item);
      prevWasBlank = false;
      continue;
    }
    flushList();

    if (!title) {
      title = line;
      prevWasBlank = false;
      continue;
    }

    // "Effective Date: ..." / "Contact: ..." style lines near the top, before
    // any section heading has been seen.
    const metaMatch = !sawFirstHeading && /^([A-Za-z][A-Za-z ]{2,30}):\s*(.+)$/.exec(line);
    if (metaMatch) {
      meta.push({ label: metaMatch[1].trim(), value: metaMatch[2].trim() });
      prevWasBlank = false;
      continue;
    }

    // Heading heuristic: the doc has no bold/heading markup at all, so infer
    // from shape — short, standalone (blank line before it), and not ending
    // in sentence punctuation. "1. Camera Data" style lines become h3s.
    const looksLikeHeading = prevWasBlank && line.length <= 70 && !/[.!?:;,]$/.test(line);

    if (looksLikeHeading) {
      sawFirstHeading = true;
      const isSubheading = /^\d+\.\s/.test(line);
      blocks.push({ type: isSubheading ? 'h3' : 'h2', text: line });
    } else {
      blocks.push({ type: 'p', text: line });
    }
    prevWasBlank = false;
  }
  flushList();

  const output = `// AUTO-GENERATED by scripts/sync-privacy-policy.mjs — do not edit by hand.
// Source: ${DOC_URL}
// Regenerate: node scripts/sync-privacy-policy.mjs

export interface PrivacyPolicyBlock {
  type: 'h2' | 'h3' | 'p' | 'ul';
  text?: string;
  items?: string[];
}

export interface PrivacyPolicyMeta {
  label: string;
  value: string;
}

export const privacyPolicy: {
  title: string;
  meta: PrivacyPolicyMeta[];
  blocks: PrivacyPolicyBlock[];
} = ${JSON.stringify({ title, meta, blocks }, null, 2)};
`;

  writeFileSync(OUTPUT_PATH, output);
  console.log(
    `Wrote ${blocks.length} blocks and ${meta.length} meta fields to ${path.relative(process.cwd(), OUTPUT_PATH)}`
  );
}

main().catch(err => {
  console.error(err.message);
  process.exit(1);
});
